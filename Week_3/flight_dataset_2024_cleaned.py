import os
import glob
import pandas as pd
import numpy as np
import kagglehub

print("=" * 70)
print("FLIGHT DATA 2024 - AUTOMATIC CLEANING")
print("=" * 70)

# 1. AUTOMATICALLY DOWNLOAD DATASET FROM KAGGLE


print("\n[1] Downloading dataset from Kaggle...")
print("Please wait - the dataset is large.")

dataset_path = kagglehub.dataset_download(
    "hrishitpatil/flight-data-2024"
)

print("\nDataset downloaded automatically!")
print("Dataset location:")
print(dataset_path)


# 2. FIND THE CSV AUTOMATICALLY


print("\n[2] Searching for CSV file...")

csv_files = glob.glob(
    os.path.join(dataset_path, "**", "*.csv"),
    recursive=True
)

if len(csv_files) == 0:
    raise FileNotFoundError(
        "No CSV file was found inside the Kaggle dataset."
    )

print("\nCSV files found:")

for file in csv_files:
    print(" -", os.path.basename(file))


# 3. SELECT THE MAIN FLIGHT CSV


flight_csv = None

for file in csv_files:

    name = os.path.basename(file).lower()

    if (
        "flight_data_2024.csv" in name
        and "sample" not in name
    ):
        flight_csv = file
        break


# If exact name is different, select largest CSV
if flight_csv is None:

    flight_csv = max(
        csv_files,
        key=os.path.getsize
    )


print("\nMain dataset selected:")
print(flight_csv)



# 4. READ HEADER ONLY


print("\n[3] Reading dataset structure...")

header = pd.read_csv(
    flight_csv,
    nrows=0
)

original_columns = list(header.columns)

print("\nOriginal number of columns:")
print(len(original_columns))

print("\nColumns:")
for i, col in enumerate(original_columns, 1):
    print(i, ":", col)



# 5. COUNT ORIGINAL ROWS


print("\n[4] Counting original rows...")

original_rows = 0

for chunk in pd.read_csv(
    flight_csv,
    usecols=[original_columns[0]],
    chunksize=500000
):
    original_rows += len(chunk)

print(
    f"Original rows: {original_rows:,}"
)

# 6. OUTPUT FILE


output_file = "/content/flight_data_2024_cleaned.csv"

# Delete previous cleaned file
if os.path.exists(output_file):
    os.remove(output_file)


# 7. CLEAN DATA IN CHUNKS


print("\n[5] Starting complete cleaning...")
print("Processing 500,000 rows at a time.")

chunk_size = 500000

total_duplicates = 0
total_invalid = 0
total_cleaned_rows = 0

first_chunk = True



# COLUMNS


delay_columns = [
    "carrier_delay",
    "weather_delay",
    "nas_delay",
    "security_delay",
    "late_aircraft_delay"
]

non_negative_columns = [
    "taxi_out",
    "taxi_in",
    "crs_elapsed_time",
    "actual_elapsed_time",
    "air_time",
    "distance",
    "carrier_delay",
    "weather_delay",
    "nas_delay",
    "security_delay",
    "late_aircraft_delay"
]

numeric_columns = [
    "year",
    "month",
    "day_of_month",
    "day_of_week",
    "op_carrier_fl_num",
    "crs_dep_time",
    "dep_time",
    "dep_delay",
    "taxi_out",
    "wheels_off",
    "wheels_on",
    "taxi_in",
    "crs_arr_time",
    "arr_time",
    "arr_delay",
    "cancelled",
    "diverted",
    "crs_elapsed_time",
    "actual_elapsed_time",
    "air_time",
    "distance",
    "carrier_delay",
    "weather_delay",
    "nas_delay",
    "security_delay",
    "late_aircraft_delay"
]




for chunk_number, df in enumerate(
    pd.read_csv(
        flight_csv,
        chunksize=chunk_size,
        low_memory=False
    ),
    start=1
):

    print(
        f"\nProcessing chunk {chunk_number}..."
    )

    rows_before = len(df)



    # STEP 1: CLEAN COLUMN NAMES


    df.columns = (
        df.columns
        .str.strip()
        .str.lower()
        .str.replace(" ", "_", regex=False)
    )


    # STEP 2: REMOVE DUPLICATES


    before = len(df)

    df = df.drop_duplicates()

    removed = before - len(df)

    total_duplicates += removed


    # STEP 3: CLEAN TEXT


    text_columns = df.select_dtypes(
        include=["object", "string"]
    ).columns

    for col in text_columns:

        df[col] = (
            df[col]
            .astype("string")
            .str.strip()
        )



    # STEP 4: CONVERT NUMERIC COLUMNS


    for col in numeric_columns:

        if col in df.columns:

            df[col] = pd.to_numeric(
                df[col],
                errors="coerce"
            )



    # STEP 5: CONVERT DATE


    if "fl_date" in df.columns:

        df["fl_date"] = pd.to_datetime(
            df["fl_date"],
            errors="coerce"
        )



    # STEP 6: FIX YEAR


    if "year" in df.columns:

        df.loc[
            df["year"] != 2024,
            "year"
        ] = np.nan


    # STEP 7: FIX MONTH


    if "month" in df.columns:

        df.loc[
            ~df["month"].between(1, 12),
            "month"
        ] = np.nan


    # STEP 8: FIX DAY


    if "day_of_month" in df.columns:

        df.loc[
            ~df["day_of_month"].between(1, 31),
            "day_of_month"
        ] = np.nan


    # STEP 9: FIX DAY OF WEEK


    if "day_of_week" in df.columns:

        df.loc[
            ~df["day_of_week"].between(1, 7),
            "day_of_week"
        ] = np.nan


    # STEP 10: FIX CANCELLED


    if "cancelled" in df.columns:

        df.loc[
            ~df["cancelled"].isin([0, 1]),
            "cancelled"
        ] = np.nan


    # STEP 11: FIX DIVERTED


    if "diverted" in df.columns:

        df.loc[
            ~df["diverted"].isin([0, 1]),
            "diverted"
        ] = np.nan



    # STEP 12: FIX NEGATIVE VALUES


    for col in non_negative_columns:

        if col in df.columns:

            df.loc[
                df[col] < 0,
                col
            ] = np.nan

    # STEP 13: HANDLE DELAY MISSING VALUES


    for col in delay_columns:

        if col in df.columns:

            df[col] = df[col].fillna(0)



    # STEP 14: HANDLE NUMERIC MISSING VALUES


    numeric_cols = df.select_dtypes(
        include=["number"]
    ).columns

    for col in numeric_cols:

        if col in delay_columns:
            continue

        if df[col].isna().any():

            median = df[col].median()

            if pd.notna(median):

                df[col] = df[col].fillna(
                    median
                )



    # STEP 15: HANDLE TEXT MISSING VALUES


    text_cols = df.select_dtypes(
        include=["object", "string"]
    ).columns

    for col in text_cols:

        df[col] = df[col].fillna(
            "UNKNOWN"
        )



    code_columns = [
        "op_unique_carrier",
        "origin",
        "dest"
    ]

    for col in code_columns:

        if col in df.columns:

            df[col] = (
                df[col]
                .astype("string")
                .str.strip()
                .str.upper()
            )




    location_columns = [
        "origin_city_name",
        "origin_state_nm",
        "dest_city_name",
        "dest_state_nm"
    ]

    for col in location_columns:

        if col in df.columns:

            df[col] = (
                df[col]
                .astype("string")
                .str.strip()
                .str.title()
            )



    if "fl_date" in df.columns:

        invalid_date = df["fl_date"].isna()

        total_invalid += invalid_date.sum()

        df = df[
            ~invalid_date
        ]



    df.to_csv(
        output_file,
        mode="w" if first_chunk else "a",
        header=first_chunk,
        index=False
    )

    first_chunk = False

    total_cleaned_rows += len(df)

    print(
        f"Rows before : {rows_before:,}"
    )

    print(
        f"Rows after  : {len(df):,}"
    )

    print(
        f"Duplicates removed : {removed:,}"
    )



print("\n[6] Performing final validation...")

final_rows = 0
final_missing = 0

for df in pd.read_csv(
    output_file,
    chunksize=500000,
    low_memory=False
):

    final_rows += len(df)

    final_missing += (
        df.isna().sum().sum()
    )



print("\n")
print("=" * 70)
